#!/usr/bin/env python3
"""Benchmark two commits of the compiler on the same problems and write a comparison table.

    python tools/compare_commits.py 2fca374 HEAD                       # problems/ and problems_extra/
    python tools/compare_commits.py 2fca374 WORKTREE                   # include uncommitted changes
    python tools/compare_commits.py 2fca374 HEAD problems -k attention
    python tools/compare_commits.py 2fca374 HEAD --out docs/perf-comparison.md

Each commit is checked out into a temporary git worktree and measured with that commit's own
tools/bench.py (warm median of --iters launches), so the numbers come from the compiler as it was
then. Raw results are written to docs/perf/<sha>.json; --reuse skips the measurement when that file exists
(useful to re-render the table). A ref is a commit, or WORKTREE for the uncommitted working tree.
Needs network access to the runner; worktrees live in a temp dir and are removed afterwards.
"""

import argparse
import json
import math
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "docs" / "perf"
WORKTREE = "WORKTREE"              # as a ref: the working tree, uncommitted changes included
SAME_BAND = 0.10                    # a change within +-10% is reported as unchanged (run-to-run noise)


def git(*args: str, cwd: Path = ROOT) -> str:
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout.strip()


def measure(ref: str, paths: list[str], iters: int, reuse: bool) -> tuple[str, dict[str, float]]:
    """(short sha, {problem: median us}) for `ref`: the cached file with --reuse, else a fresh worktree run."""
    sha = "worktree" if ref == WORKTREE else git("rev-parse", "--short", ref)
    cached = CACHE / f"{sha}.json"
    if reuse and cached.exists():
        return sha, json.loads(cached.read_text())
    with tempfile.TemporaryDirectory() as scratch:
        out = Path(scratch) / "result.json"
        bench = [sys.executable, "tools/bench.py", *paths, "--iters", str(iters), "--json", str(out)]
        if ref == WORKTREE:                              # uncommitted changes, measured where they are
            subprocess.run(bench, cwd=ROOT, check=True)
        else:
            tree = Path(scratch) / sha
            git("worktree", "add", "--detach", str(tree), sha)
            try:
                subprocess.run(bench, cwd=tree, check=True)
            finally:
                git("worktree", "remove", "--force", str(tree))
        results = json.loads(out.read_text())
    CACHE.mkdir(parents=True, exist_ok=True)
    cached.write_text(json.dumps(results, indent=1, sort_keys=True))
    return sha, results


def classify(speedup: float) -> str:
    if speedup > 1 + SAME_BAND:
        return "faster"
    return "slower" if speedup < 1 / (1 + SAME_BAND) else "same"


def table(base: dict[str, float], head: dict[str, float], names: list[str]) -> str:
    rows = sorted(names, key=lambda n: base[n] / head[n], reverse=True)
    lines = ["| problem | base (us) | head (us) | speed-up |", "|---|---:|---:|---:|"]
    lines += [f"| {n} | {base[n]:.1f} | {head[n]:.1f} | {base[n] / head[n]:.2f}x |" for n in rows]
    return "\n".join(lines)


def report(base_sha: str, head_sha: str, base: dict[str, float], head: dict[str, float], iters: int) -> str:
    names = sorted(set(base) & set(head))
    speedups = {n: base[n] / head[n] for n in names}
    counts = {k: sum(classify(s) == k for s in speedups.values()) for k in ("faster", "same", "slower")}
    geomean = math.exp(sum(math.log(s) for s in speedups.values()) / len(speedups))
    moved = [n for n in names if classify(speedups[n]) != "same"]
    return "\n".join([
        f"# Performance: `{base_sha}` -> `{head_sha}`",
        "",
        f"Warm median of {iters} launches per problem on the runner (`tools/bench.py`), single-kernel problems only. "
        f"Generated by `tools/compare_commits.py {base_sha} {head_sha}`; a change within "
        f"+-{SAME_BAND:.0%} counts as unchanged (run-to-run noise on short kernels).",
        "",
        f"- {len(names)} problems measured: **{counts['faster']} faster, {counts['same']} unchanged, "
        f"{counts['slower']} slower**",
        f"- geometric mean speed-up over all of them: **{geomean:.2f}x**",
        f"- best: {max(speedups, key=speedups.get)} ({max(speedups.values()):.2f}x), "
        f"worst: {min(speedups, key=speedups.get)} ({min(speedups.values()):.2f}x)",
        "",
        "## Problems that changed",
        "",
        table(base, head, moved) if moved else "None.",
        "",
        "## All problems",
        "",
        table(base, head, names),
        "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("base", help="git ref of the baseline, e.g. 2fca374")
    parser.add_argument("head", nargs="?", default="HEAD", help="git ref to compare against (default HEAD)")
    parser.add_argument("paths", nargs="*", default=["problems", "problems_extra"],
                        help="problem folders, or folders of problem folders")
    parser.add_argument("--iters", type=int, default=100)
    parser.add_argument("--out", default="docs/perf-comparison.md", help="markdown file to write")
    parser.add_argument("--reuse", action="store_true", help="use docs/perf/<sha>.json when it exists")
    args = parser.parse_args()

    base_sha, base = measure(args.base, args.paths, args.iters, args.reuse)
    head_sha, head = measure(args.head, args.paths, args.iters, args.reuse)
    text = report(base_sha, head_sha, base, head, args.iters)
    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text.split("## Problems that changed")[0])
    print(f"written to {args.out}")


if __name__ == "__main__":
    main()
