#!/usr/bin/env python3
"""Regenerate examples/compiled/: the compiler's PTX beside the Kernel IR it came from.

    python tools/make_examples.py          # rewrite the files
    python tools/make_examples.py --check  # exit 1 if any committed file is stale
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from compile import compile_ir  # noqa: E402

OUT = ROOT / "examples" / "compiled"

# name -> (problem folder, kernel IR file, what it shows)
EXAMPLES = {
    "pointwise_vector": ("problems/p02_scale_shift", "k_add_pointwise",
                         "unrolled body, constants as 1-element buffers, one v4 store; explicit .rn so ptxas cannot fuse mul+add"),
    "reduction": ("problems/r04_row_sum", "k_sum_1_reduce",
                  "strided loop with an in-place accumulator, warp butterfly, shared-memory tree, guarded write"),
    "matmul_cp_async": ("problems/m02_matmul_rect", "k_matmul",
                        "cp.async copies into shared memory, commit/wait groups, split-K with atomic writes"),
    "fused_softmax": ("problems/f02_row_softmax", "k_softmax_05263d",
                      "online softmax: two coupled accumulators through WarpShuffle and TreeHalve"),
    "f16_tensor_core": ("problems_extra/z_h_matmul", "k_matmul__partial",
                        "mma.sync m16n8k16 with ldmatrix, B64-swizzled cp.async, double-buffered, f16 in / f32 accumulate"),
    "f16_attention": ("problems_extra/w_h_attn_64", "k_matmul_softmax_reduce_85756c",
                      "fused flash attention on tensor cores: fragment pointwise ops, row reductions, C-to-A repack"),
    "tma": ("problems_asm/t_h_mm_tma", "k_matmul_88f287",
            "TMA bulk-tensor copies with mbarriers and a tensor-map parameter (assembled with ptxas, not executed)"),
}


def render_all() -> dict[Path, str]:
    files = {}
    for name, (folder, kernel, _) in EXAMPLES.items():
        directory = ROOT / folder
        files[OUT / f"{name}.ptx"] = compile_ir(str(directory / f"{kernel}.ir.json"))
        ir_text = directory / f"{kernel}.ir.txt"
        if ir_text.exists():
            files[OUT / f"{name}.ir.txt"] = ir_text.read_text()
    lines = ["# Compiled examples", "",
             "Generated by `tools/make_examples.py`. Each `<name>.ptx` is this compiler's output for the kernel whose",
             "pretty-printed IR is in `<name>.ir.txt`.", ""]
    lines += [f"- **{name}** (`{folder}`): {note}" for name, (folder, _, note) in EXAMPLES.items()]
    files[OUT / "README.md"] = "\n".join(lines) + "\n"
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files instead of writing")
    args = parser.parse_args()
    files = render_all()
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text)
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
